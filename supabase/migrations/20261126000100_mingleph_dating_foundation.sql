  for delete to authenticated using (sender_id = (select auth.uid()));

-- Matches have read access only. Creation and conversation provisioning require
-- a trusted Edge Function after checking reciprocal likes and block status.
create policy matches_read_participants on public.matches
  for select to authenticated
  using ((user_one_id = (select auth.uid()) or user_two_id = (select auth.uid()))
    and not private.is_blocked_with(case when user_one_id = (select auth.uid()) then user_two_id else user_one_id end));
create policy conversations_read_members on public.conversations
  for select to authenticated
  using (private.is_conversation_member(id) and private.conversation_has_no_blocked_member(id));
create policy conversation_members_read_members on public.conversation_members
  for select to authenticated
  using (private.is_conversation_member(conversation_id)
    and private.conversation_has_no_blocked_member(conversation_id));

create policy messages_read_members on public.messages
  for select to authenticated
  using (private.is_conversation_member(conversation_id)
    and private.conversation_has_no_blocked_member(conversation_id));
create policy messages_insert_as_self on public.messages
  for insert to authenticated
  with check (sender_id = (select auth.uid())
    and private.is_conversation_member(conversation_id)
    and private.conversation_has_no_blocked_member(conversation_id));
create policy messages_update_read_receipt on public.messages
  for update to authenticated
  using (sender_id <> (select auth.uid())
    and private.is_conversation_member(conversation_id)
    and private.conversation_has_no_blocked_member(conversation_id))
  with check (sender_id <> (select auth.uid())
    and private.is_conversation_member(conversation_id)
    and private.conversation_has_no_blocked_member(conversation_id));

