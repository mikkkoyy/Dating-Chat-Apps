-- MinglePH dating-data foundation. Exact birth dates are private; the public
-- profiles table intentionally contains only discoverable profile fields.
begin;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  display_name text not null,
  gender text,
  bio text not null default '',
  -- Store only a broad city/region here; never persist precise coordinates.
  location text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (username ~ '^[A-Za-z0-9_]{3,30}$'),
  constraint profiles_display_name_length check (char_length(display_name) between 1 and 80),
  constraint profiles_bio_length check (char_length(bio) <= 500),
  constraint profiles_location_length check (location is null or char_length(location) <= 120)
);
create unique index if not exists profiles_username_lower_unique
  on public.profiles (lower(username));

-- Split sensitive date-of-birth data out of discoverable profile rows.
create table if not exists public.profile_private (
  user_id uuid primary key references auth.users(id) on delete cascade,
  birth_date date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profile_private_adult check (birth_date <= current_date - interval '18 years'),
  constraint profile_private_birth_date_sane check (birth_date >= date '1900-01-01')
);

create table if not exists public.profile_photos (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  -- Storage object path; clients obtain short-lived signed URLs when needed.
  photo_path text not null unique,
  display_order smallint not null default 0 check (display_order between 0 and 20),
  created_at timestamptz not null default now(),
  constraint profile_photos_path_owner check (split_part(photo_path, '/', 1) = user_id::text),
  unique (user_id, display_order)
);
create index if not exists profile_photos_user_order_idx
  on public.profile_photos (user_id, display_order);

create table if not exists public.interests (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 60),
  created_at timestamptz not null default now()
);

create table if not exists public.user_interests (
  user_id uuid not null references auth.users(id) on delete cascade,
  interest_id bigint not null references public.interests(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, interest_id)
);
create index if not exists user_interests_interest_idx
  on public.user_interests (interest_id, user_id);

create table if not exists public.user_blocks (
  blocker_id uuid not null references auth.users(id) on delete cascade,
  blocked_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  constraint user_blocks_not_self check (blocker_id <> blocked_id)
);
create index if not exists user_blocks_blocked_idx on public.user_blocks (blocked_id, blocker_id);

create table if not exists public.likes (
  id uuid primary key default gen_random_uuid(),
  sender_id uuid not null references auth.users(id) on delete cascade,
  receiver_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint likes_not_self check (sender_id <> receiver_id),
  unique (sender_id, receiver_id)
);
create index if not exists likes_receiver_created_idx
  on public.likes (receiver_id, created_at desc);

create table if not exists public.matches (
  id uuid primary key default gen_random_uuid(),
  user_one_id uuid not null references auth.users(id) on delete cascade,
  user_two_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint matches_distinct_users check (user_one_id < user_two_id),
  unique (user_one_id, user_two_id)
);
create index if not exists matches_user_two_idx on public.matches (user_two_id, created_at desc);

create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  conversation_type text not null default 'direct'
    check (conversation_type in ('direct', 'group')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.conversation_members (
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (conversation_id, user_id)
);
create index if not exists conversation_members_user_idx
  on public.conversation_members (user_id, conversation_id);

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  message_type text not null default 'text'
    check (message_type in ('text', 'image', 'voice')),
  content text,
  media_path text,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  constraint messages_payload check (
    (message_type = 'text' and content is not null and char_length(content) between 1 and 4000 and media_path is null)
    or (message_type in ('image', 'voice') and media_path is not null and content is null
      and split_part(media_path, '/', 1) = conversation_id::text
      and split_part(media_path, '/', 2) = sender_id::text)
  ),
  constraint messages_media_path_owner check (
    message_type = 'text' or split_part(media_path, '/', 2) = sender_id::text
  )
);
create index if not exists messages_conversation_created_idx
  on public.messages (conversation_id, created_at desc, id);
create index if not exists messages_sender_idx on public.messages (sender_id, created_at desc);

create table if not exists public.user_reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reported_user_id uuid not null references auth.users(id) on delete cascade,
  reason text not null check (char_length(reason) between 1 and 120),
  details text not null default '' check (char_length(details) <= 4000),
  status text not null default 'pending'
    check (status in ('pending', 'reviewing', 'resolved', 'dismissed')),
  created_at timestamptz not null default now(),
  constraint user_reports_not_self check (reporter_id <> reported_user_id)
);
create index if not exists user_reports_reported_status_idx
  on public.user_reports (reported_user_id, status, created_at desc);

create or replace function private.is_blocked_with(p_other_user uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.user_blocks b
    where (b.blocker_id = (select auth.uid()) and b.blocked_id = p_other_user)
       or (b.blocker_id = p_other_user and b.blocked_id = (select auth.uid()))
  );
$$;

create or replace function private.is_conversation_member(p_conversation_id uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.conversation_members cm
    where cm.conversation_id = p_conversation_id and cm.user_id = (select auth.uid())
  );
$$;

create or replace function private.conversation_has_no_blocked_member(p_conversation_id uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select private.is_conversation_member(p_conversation_id)
    and not exists (
    select 1 from public.conversation_members cm
    where cm.conversation_id = p_conversation_id
      and cm.user_id <> (select auth.uid())
      and private.is_blocked_with(cm.user_id)
  );
$$;

revoke all on function private.is_blocked_with(uuid) from public, anon;
revoke all on function private.is_conversation_member(uuid) from public, anon;
revoke all on function private.conversation_has_no_blocked_member(uuid) from public, anon;
grant execute on function private.is_blocked_with(uuid) to authenticated;
grant execute on function private.is_conversation_member(uuid) to authenticated;
grant execute on function private.conversation_has_no_blocked_member(uuid) to authenticated;

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
revoke all on function public.set_updated_at() from public, anon, authenticated;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles
for each row execute function public.set_updated_at();
drop trigger if exists profile_private_set_updated_at on public.profile_private;
create trigger profile_private_set_updated_at before update on public.profile_private
for each row execute function public.set_updated_at();
drop trigger if exists conversations_set_updated_at on public.conversations;
create trigger conversations_set_updated_at before update on public.conversations
for each row execute function public.set_updated_at();

